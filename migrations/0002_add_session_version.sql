-- F-04 需要：会话版本号。改密时 +1，使所有旧会话失效。
-- 默认值 0，与代码里 sessVersion() 对旧会话值（无冒号）返回 0 的行为一致，
-- 因此部署后【现有会话不会立即失效】，用户需重新登录一次才带上版本号。
ALTER TABLE users ADD COLUMN session_version INTEGER NOT NULL DEFAULT 0;
